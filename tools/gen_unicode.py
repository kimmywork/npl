#!/usr/bin/env python3
"""Generate NPL's Unicode tables from the host Python's unicodedata.

Usage: python3 tools/gen_unicode.py

Writes runtime/unicode_tables.h. The Unicode version is the one Python
reports (docs/design-l6.md, Decision 4) and is recorded in the output.
Regenerate after a Python upgrade and commit the result.
"""

import os
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Characters `write` prints with hex escapes, as Guile does: the general
# categories Cc Cf Cs Co Cn Zs Zl Zp, except U+0020 SPACE.
NONGRAPHIC = {"Cc", "Cf", "Cs", "Co", "Cn", "Zs", "Zl", "Zp"}


def ranges(predicate):
    result, start = [], None
    for code in range(0x110000):
        inside = predicate(code)
        if inside and start is None:
            start = code
        elif not inside and start is not None:
            result.append((start, code - 1))
            start = None
    if start is not None:
        result.append((start, 0x10FFFF))
    return result


def c_table(name, items):
    lines = ["static const uint32_t %s[][2] = {" % name]
    row = []
    for low, high in items:
        row.append("{0x%X, 0x%X}," % (low, high))
        if len(row) == 4:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("};")
    return "\n".join(lines)


def main():
    nongraphic = ranges(lambda c: c != 0x20 and
                        unicodedata.category(chr(c)) in NONGRAPHIC)
    text = "\n".join([
        "/* Generated by tools/gen_unicode.py from Python unicodedata %s."
        % unicodedata.unidata_version,
        " * Do not edit. */",
        "",
        "#define NPL_UNICODE_VERSION \"%s\"" % unicodedata.unidata_version,
        "",
        "/* write escapes these (sorted, inclusive ranges). */",
        c_table("npl_nongraphic_ranges", nongraphic),
        "",
    ])
    with open(os.path.join(ROOT, "runtime", "unicode_tables.h"), "w") as out:
        out.write(text)


if __name__ == "__main__":
    main()
